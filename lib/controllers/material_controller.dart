import 'dart:io';

import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:flutter/foundation.dart';
import 'package:sqflite/sqflite.dart';

import '../services/database_service.dart';
import '../services/material_service.dart';

class MaterialController {

  final MaterialService _materialService = MaterialService();

  /// Sync materials of ONE chapter from Firestore to SQLite.
  Future<List<Map<String, dynamic>>> syncMaterials(
      String chapterId,
      ) async {
    await syncMaterialsForChapters([chapterId]);
    return _materialService.getMaterialsByChapter(chapterId);
  }

  /// CHANGED: syncs the materials of MANY chapters with as few
  /// Firestore queries as possible (whereIn, max 30 ids per
  /// query) instead of one query per chapter.
  ///
  /// Files that were already downloaded for offline use are
  /// kept (local_path is preserved), so a refresh does not
  /// download them again. Files of materials that were removed
  /// or replaced are deleted from the phone.
  Future<void> syncMaterialsForChapters(
      List<String> chapterIds,
      ) async {
    if (chapterIds.isEmpty) return;

    final docs = <QueryDocumentSnapshot<Map<String, dynamic>>>[];

    for (var i = 0; i < chapterIds.length; i += 30) {
      final end = (i + 30 < chapterIds.length) ? i + 30 : chapterIds.length;
      final chunk = chapterIds.sublist(i, end);

      final snapshot = await FirebaseFirestore.instance
          .collection('materials')
          .where('chapter_id', whereIn: chunk)
          .get();

      docs.addAll(snapshot.docs);
    }

    final db = await DatabaseService.instance.database;
    final placeholders = List.filled(chapterIds.length, '?').join(',');

    // What is stored on the phone right now
    final existingRows = await db.query(
      'materials',
      where: 'chapter_id IN ($placeholders)',
      whereArgs: chapterIds,
    );

    final existing = <String, Map<String, dynamic>>{
      for (final row in existingRows) row['id'] as String: row,
    };

    final filesToDelete = <String>[];
    final newIds = <String>{};

    await db.transaction((txn) async {
      final batch = txn.batch();

      for (final doc in docs) {
        final material = doc.data();
        final ecoPath = (material['eco_file_path'] ?? '').toString();

        newIds.add(doc.id);

        String localPath = '';
        String localMode = '';

        final old = existing[doc.id];
        if (old != null) {
          final oldLocal = (old['local_path'] ?? '').toString();

          if ((old['eco_file_path'] ?? '').toString() == ecoPath) {
            // Same optimised file -> keep the downloaded copy
            localPath = oldLocal;
            localMode = (old['local_mode'] ?? '').toString();
          } else if (oldLocal.isNotEmpty) {
            // Optimised file changed -> old copy is out of date
            filesToDelete.add(oldLocal);
          }
        }

        batch.insert(
          'materials',
          {
            'id': doc.id,
            'chapter_id': material['chapter_id'],
            'title': material['title'],
            'description': material['description'],
            'type': material['type'],
            'file_name': material['file_name'],
            'file_url': material['file_url'],
            // Optimised file generated by the Cloud Function
            'eco_file_path': ecoPath,
            'local_path': localPath,
            'local_mode': localMode,
          },
          conflictAlgorithm: ConflictAlgorithm.replace,
        );
      }

      // Materials that no longer exist in Firestore
      for (final entry in existing.entries) {
        if (newIds.contains(entry.key)) continue;

        final oldLocal = (entry.value['local_path'] ?? '').toString();
        if (oldLocal.isNotEmpty) filesToDelete.add(oldLocal);

        batch.delete(
          'materials',
          where: 'id = ?',
          whereArgs: [entry.key],
        );
      }

      await batch.commit(noResult: true);
    });

    for (final path in filesToDelete) {
      try {
        final file = File(path);
        if (await file.exists()) await file.delete();
      } catch (e) {
        debugPrint('Could not delete old file $path: $e');
      }
    }
  }

  /// Load materials from SQLite only
  Future<List<Map<String, dynamic>>> getSQLiteMaterials(
      String chapterId,
      ) async {
    return await _materialService
        .getMaterialsByChapter(chapterId);
  }
}
